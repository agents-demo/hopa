#!/usr/bin/env python3
"""Generate the approval vocabularies from the shared contract.

Source of truth: ``contracts/policy/approval.v1.json``.
The ArkTS output is committed so the Harmony app needs no JSON parsing at
runtime. The Kotlin output is emitted with ``--kotlin PATH`` for the Android
client; its build generates and commits its own copy (ADR-0018, ADR-0020).

Every client loop reads the same lists: a payment word or a sensitive kind added
for one platform must not silently stay out of another.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "contracts" / "policy" / "approval.v1.json"
TARGET = (
    ROOT
    / "apps"
    / "harmony"
    / "core"
    / "src"
    / "main"
    / "ets"
    / "gate"
    / "PolicyData.ets"
)

LISTS = (
    ("PAYMENT_KINDS", "paymentKinds"),
    ("PAYMENT_WORDS", "paymentWords"),
    ("PAYMENT_ACTIONS", "paymentActions"),
    ("INTERACTIVE_KINDS", "interactiveKinds"),
    ("SENSITIVE_KINDS", "sensitiveKinds"),
    ("ALLOWED_KINDS", "allowedKinds"),
    ("TRUSTED_APP_KINDS", "trustedAppKinds"),
    ("MERCHANT_PREFIXES", "merchantPrefixes"),
)


def load() -> dict:
    return json.loads(SOURCE.read_text(encoding="utf-8"))


def string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def kotlin_string(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("$", "\\$")
        .replace("\n", "\\n")
        .replace("\r", "\\r")
    )
    return f'"{escaped}"'


def values_for(data: dict, key: str) -> list[str]:
    return data["payment"][key] if key == "merchantPrefixes" else data[key]


def render(data: dict) -> str:
    payment = data["payment"]
    lines = [
        "// Generated by tools/scripts/build-policy-data.py. Do not edit by hand.",
        "// Source: contracts/policy/approval.v1.json",
        "",
    ]
    for constant, key in LISTS:
        values = values_for(data, key)
        lines.append(f"export const {constant}: string[] = [")
        for value in values:
            lines.append(f"  {string(value)},")
        lines.append("];")
    lines.extend(
        [
            "",
            f"export const CURRENCY_RE: RegExp = /{payment['currencyPattern']}/{payment['currencyFlags']};",
            f"export const CURRENCY_TOKEN_RE: RegExp = /{payment['currencyTokenPattern']}/{payment['currencyTokenFlags']};",
            f"export const TOTAL_RE: RegExp = /{payment['totalPattern']}/{payment['totalFlags']};",
            f"export const PAYMENT_CONSEQUENCE: string = {string(payment['consequence'])};",
            "",
        ]
    )
    return "\n".join(lines)


def render_kotlin(data: dict) -> str:
    payment = data["payment"]
    lines = [
        "// Generated by tools/scripts/build-policy-data.py. Do not edit by hand.",
        "// Source: contracts/policy/approval.v1.json",
        "package com.hopa.policy",
        "",
        "object ApprovalPolicyData {",
    ]
    for constant, key in LISTS:
        values = values_for(data, key)
        lines.append(f"    val {constant}: List<String> = listOf(")
        for value in values:
            lines.append(f"        {kotlin_string(value)},")
        lines.append("    )")
    lines.extend(
        [
            "",
            f"    val CURRENCY_RE: Regex = Regex({kotlin_string(payment['currencyPattern'])}, RegexOption.IGNORE_CASE)",
            f"    val CURRENCY_TOKEN_RE: Regex = Regex({kotlin_string(payment['currencyTokenPattern'])}, RegexOption.IGNORE_CASE)",
            f"    val TOTAL_RE: Regex = Regex({kotlin_string(payment['totalPattern'])}, RegexOption.IGNORE_CASE)",
            f"    const val PAYMENT_CONSEQUENCE: String = {kotlin_string(payment['consequence'])}",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def option_path(name: str) -> Path | None:
    if name not in sys.argv:
        return None
    index = sys.argv.index(name)
    if index + 1 >= len(sys.argv):
        raise SystemExit(f"{name} needs a path")
    return Path(sys.argv[index + 1])


def main() -> int:
    data = load()
    output = render(data)
    kotlin_path = option_path("--kotlin")
    kotlin_output = render_kotlin(data) if kotlin_path is not None else ""

    if "--check" in sys.argv:
        stale = []
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != output:
            stale.append(TARGET)
        if kotlin_path is not None and (
            not kotlin_path.exists()
            or kotlin_path.read_text(encoding="utf-8") != kotlin_output
        ):
            stale.append(kotlin_path)
        if stale:
            for path in stale:
                print(
                    f"{path} is stale; run tools/scripts/build-policy-data.py",
                    file=sys.stderr,
                )
            return 1
        print(f"policy data is current ({len(data['allowedKinds'])} allowed kinds)")
        return 0

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(output, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    if kotlin_path is not None:
        kotlin_path.parent.mkdir(parents=True, exist_ok=True)
        kotlin_path.write_text(kotlin_output, encoding="utf-8", newline="\n")
        print(f"wrote {kotlin_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
