#!/usr/bin/env python3
"""Generate the prompt-rule list from the shared contract.

Source of truth: ``contracts/prompts/rules.v1.json``.
The ArkTS output is committed. ``--kotlin PATH`` emits the same rules for the
Android client; its build generates and commits its own copy (ADR-0018).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "contracts" / "prompts" / "rules.v1.json"
TARGET = (
    ROOT
    / "apps"
    / "harmony"
    / "core"
    / "src"
    / "main"
    / "ets"
    / "agent"
    / "PromptRules.ets"
)


def string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def kotlin_string(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("$", "\\$")
        .replace("\n", "\\n")
        .replace("\r", "\\r")
    )
    return f'"{escaped}"'


def render(data: dict) -> str:
    lines = [
        "// Generated by tools/scripts/build-prompt-rules.py. Do not edit by hand.",
        "// Source: contracts/prompts/rules.v1.json",
        "",
        "export class PromptRule {",
        "  id: string = '';",
        "  phrases: string[] = [];",
        "}",
        "",
        "export const PROMPT_RULES: PromptRule[] = [",
    ]
    for rule in data["rules"]:
        lines.append("  {")
        lines.append(f"    id: {string(rule['id'])},")
        lines.append("    phrases: [")
        for phrase in rule["phrases"]:
            lines.append(f"      {string(phrase)},")
        lines.append("    ],")
        lines.append("  },")
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def render_kotlin(data: dict) -> str:
    lines = [
        "// Generated by tools/scripts/build-prompt-rules.py. Do not edit by hand.",
        "// Source: contracts/prompts/rules.v1.json",
        "package com.hopa.prompt",
        "",
        "data class PromptRule(val id: String, val phrases: List<String>)",
        "",
        "val PROMPT_RULES: List<PromptRule> = listOf(",
    ]
    for rule in data["rules"]:
        lines.append("    PromptRule(")
        lines.append(f"        id = {kotlin_string(rule['id'])},")
        lines.append("        phrases = listOf(")
        for phrase in rule["phrases"]:
            lines.append(f"            {kotlin_string(phrase)},")
        lines.append("        ),")
        lines.append("    ),")
    lines.append(")")
    lines.append("")
    return "\n".join(lines)


def option_path(name: str) -> Path | None:
    if name not in sys.argv:
        return None
    index = sys.argv.index(name)
    if index + 1 >= len(sys.argv):
        raise SystemExit(f"{name} needs a path")
    return Path(sys.argv[index + 1])


def main() -> int:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    output = render(data)
    kotlin_path = option_path("--kotlin")
    kotlin_output = render_kotlin(data) if kotlin_path is not None else ""

    if "--check" in sys.argv:
        stale = []
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != output:
            stale.append(TARGET)
        if kotlin_path is not None and (
            not kotlin_path.exists()
            or kotlin_path.read_text(encoding="utf-8") != kotlin_output
        ):
            stale.append(kotlin_path)
        if stale:
            for path in stale:
                print(
                    f"{path} is stale; run tools/scripts/build-prompt-rules.py",
                    file=sys.stderr,
                )
            return 1
        print(f"prompt rules are current ({len(data['rules'])} rules)")
        return 0

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(output, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    if kotlin_path is not None:
        kotlin_path.parent.mkdir(parents=True, exist_ok=True)
        kotlin_path.write_text(kotlin_output, encoding="utf-8", newline="\n")
        print(f"wrote {kotlin_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
