#!/usr/bin/env python3
"""Generate the ArkTS prompt-rule list from the shared contract.

Source of truth: ``contracts/prompts/rules.v1.json``.
The Android client generates its own constant from the same file (ADR-0018).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "contracts" / "prompts" / "rules.v1.json"
TARGET = (
    ROOT
    / "apps"
    / "harmony"
    / "core"
    / "src"
    / "main"
    / "ets"
    / "agent"
    / "PromptRules.ets"
)


def string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def render(data: dict) -> str:
    lines = [
        "// Generated by tools/scripts/build-prompt-rules.py. Do not edit by hand.",
        "// Source: contracts/prompts/rules.v1.json",
        "",
        "export class PromptRule {",
        "  id: string = '';",
        "  phrases: string[] = [];",
        "}",
        "",
        "export const PROMPT_RULES: PromptRule[] = [",
    ]
    for rule in data["rules"]:
        lines.append("  {")
        lines.append(f"    id: {string(rule['id'])},")
        lines.append("    phrases: [")
        for phrase in rule["phrases"]:
            lines.append(f"      {string(phrase)},")
        lines.append("    ],")
        lines.append("  },")
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    output = render(data)
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != output:
            print(
                f"{TARGET} is stale; run tools/scripts/build-prompt-rules.py",
                file=sys.stderr,
            )
            return 1
        print(f"prompt rules are current ({len(data['rules'])} rules)")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(output, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
