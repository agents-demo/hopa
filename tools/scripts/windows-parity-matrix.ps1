param(
    [string]$Output = "out/windows-parity",
    [switch]$SkipBuild,
    [switch]$SkipAndroid
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
Set-Location $root
$out = Join-Path $root $Output
$windows = Join-Path $out "windows"
$android = Join-Path $out "android"
New-Item -ItemType Directory -Path $windows, $android -Force | Out-Null

function Assert-LastExit([string]$name) {
    if ($null -ne $LASTEXITCODE -and $LASTEXITCODE -ne 0) {
        throw "$name exited with code $LASTEXITCODE"
    }
}

if (-not $SkipBuild) {
    dotnet build apps/windows/Hopa.Windows.DevTools -c Release --nologo
    Assert-LastExit "DevTools build"
}

$dev = Join-Path $root "apps/windows/Hopa.Windows.DevTools/bin/Release/net10.0-windows/Hopa.Windows.DevTools.exe"
if (-not (Test-Path $dev)) {
    throw "DevTools is not built at $dev"
}

Write-Host "windows screenshots"
& $dev --shot-settings-pages $windows
Assert-LastExit "settings pages"
& $dev --shot-chat $windows
Assert-LastExit "chat"
& $dev --shot-components $windows
Assert-LastExit "components"
& $dev --shot-frame (Join-Path $windows "windows-frame.png")
Assert-LastExit "frame"
& $dev --shot-settings (Join-Path $windows "windows-settings.png")
Assert-LastExit "settings"
& $dev --w4-check (Join-Path $windows "w4")
Assert-LastExit "w4"
& $dev --web-check (Join-Path $windows "web")
Assert-LastExit "web"

if (-not $SkipAndroid) {
    Write-Host "android screenshots"
    Push-Location (Join-Path $root "apps/android")
    try {
        & .\gradlew.bat :screenshots:verifyRoborazziDebug --no-daemon
        Assert-LastExit "Roborazzi"
    }
    finally {
        Pop-Location
    }

    $roborazzi = Join-Path $root "apps/android/screenshots/build/outputs/roborazzi"
    if (Test-Path $roborazzi) {
        Copy-Item (Join-Path $roborazzi "*.png") $android -Force
    }
    else {
        Write-Warning "Roborazzi produced no files at $roborazzi"
    }
}

$rows = @(
    "# Windows semantic-parity screenshot matrix",
    "",
    'Generated by `tools/scripts/windows-parity-matrix.ps1`.',
    "",
    "| Side | File | Bytes |",
    "|---|---|---:|"
)
foreach ($side in @(@("windows", $windows), @("android", $android))) {
    $label = $side[0]
    $directory = $side[1]
    $files = Get-ChildItem -Path $directory -Recurse -File -Filter *.png -ErrorAction SilentlyContinue |
        Sort-Object FullName
    foreach ($file in $files) {
        $relative = $file.FullName.Substring($out.Length + 1).Replace('\', '/')
        $rows += "| $label | $relative | $($file.Length) |"
    }
}
$rows += @(
    "",
    'The matrix pairs Android `_actual.png`/`_compare.png` files with the Windows',
    'surface named in `docs/project/plan/windows/parity.md`. Rows that are',
    '`adapt` or `new` explain the desktop form; `not-applicable` rows carry the',
    "platform reason. This script does not invent a missing screenshot."
)
Set-Content -Path (Join-Path $out "index.md") -Value $rows -Encoding utf8
Write-Host "wrote $(Join-Path $out 'index.md')"
