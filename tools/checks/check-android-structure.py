#!/usr/bin/env python3
"""Enforce the Android source structure the plan promises.

Rules:
  * a Kotlin package matches its folder under ``src/*/kotlin``;
  * one public top-level declaration per file, and the file is named after it;
  * no ``Utils``/``Helpers``/``Common``/``Manager`` file names;
  * everything under ``packages/`` (the client engine) imports no ``android.*``
    or ``androidx.*``.

The check covers both the Android app and the shared packages, so a module that
moves between them keeps the same rules.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ANDROID = ROOT / "apps" / "android"
PACKAGES = ROOT / "packages"
BANNED = {"Utils", "Helpers", "Common", "Manager", "Misc"}
DECL = re.compile(
    r"^(?:public |internal |private |protected )?"
    r"(?:data |sealed |enum |abstract |open |annotation )?"
    r"(class|interface|object|fun) ([A-Za-z_][A-Za-z0-9_]*)",
)
PACKAGE = re.compile(r"^package ([A-Za-z0-9_.]+)")
VISIBILITY = re.compile(r"^(?:private |internal |protected )")


def kotlin_files() -> list[Path]:
    return sorted(
        list(ANDROID.glob("**/src/*/kotlin/**/*.kt"))
        + list(PACKAGES.glob("*/src/*/kotlin/**/*.kt"))
    )


def relative_package(path: Path) -> str | None:
    parts = path.parts
    if "kotlin" not in parts:
        return None
    index = parts.index("kotlin")
    folders = parts[index + 1 : -1]
    return ".".join(folders)


def check() -> list[str]:
    problems: list[str] = []
    for path in kotlin_files():
        text = path.read_text(encoding="utf-8").lstrip("\ufeff")
        if path.stem in BANNED:
            problems.append(f"{path.relative_to(ROOT)}: banned file name")
        expected = relative_package(path)
        package = next(
            (PACKAGE.match(line).group(1) for line in text.splitlines() if PACKAGE.match(line)),
            "",
        )
        if expected and package != expected:
            problems.append(
                f"{path.relative_to(ROOT)}: package {package!r} does not match {expected!r}"
            )
        generated = text.startswith("// Generated by")
        declarations: list[tuple[str, str]] = []
        for line in text.splitlines():
            match = DECL.match(line)
            if not match:
                continue
            if VISIBILITY.match(line) and not line.startswith("internal "):
                continue
            declarations.append((match.group(1), match.group(2)))
        if not generated and declarations:
            if len(declarations) > 1:
                problems.append(
                    f"{path.relative_to(ROOT)}: {len(declarations)} public declarations "
                    f"{declarations}"
                )
            else:
                kind, name = declarations[0]
                if path.stem != name:
                    problems.append(
                        f"{path.relative_to(ROOT)}: file name does not match {kind} {name}"
                    )
        relative = path.relative_to(ROOT)
        if relative.parts[0] == "packages":
            for number, line in enumerate(text.splitlines(), 1):
                stripped = line.strip()
                if stripped.startswith("import android.") or stripped.startswith("import androidx."):
                    problems.append(
                        f"{relative}:{number}: a client package imports Android"
                    )
    return problems


def main() -> int:
    problems = check()
    for problem in problems:
        print(f"FAIL  {problem}")
    print(f"{len(problems)} Android structure problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
